#!/usr/bin/env python3
"""Isolated raw-TCP/TLS probe for ACK-window-induced TLS stream desynchronization.

A valid TLS 1.3 application record is generated by OpenSSL MemoryBIO. The test
sends a deliberately corrupted 16-byte prefix with an out-of-window TCP ACK,
then retransmits the original complete record at its original TCP sequence.
The frozen target consumes the prefix before TLS authentication; fixed targets
reject it and accept the complete authenticated record.
"""
from __future__ import annotations

import os
import select
import socket
import ssl
import struct
import sys
import time
from pathlib import Path

if len(sys.argv) != 3:
    raise SystemExit("usage: test_tls_tcp_ack_desync.py TARGET [expect|reject]")

mode = sys.argv[2]
if mode not in {"expect", "reject"}:
    raise SystemExit("mode must be expect or reject")
EXPECT_DESYNC = mode == "expect"

target = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(target / "tools"))
import tlsclient  # noqa: E402

GUEST_IP = socket.inet_aton("10.0.2.15")
HOST_IP = socket.inet_aton("10.64.0.1")
TAP = os.environ.get("TAP", "k2t")
SPORT = 52443
ISN = 0x5A6B7C8D
REQUEST = (
    f"GET / HTTP/1.1\r\nHost: {tlsclient.NAME}\r\n"
    "Connection: close\r\n\r\n"
).encode("ascii")


def checksum(data: bytes) -> int:
    if len(data) & 1:
        data += b"\0"
    total = sum(struct.unpack("!%dH" % (len(data) // 2), data))
    while total >> 16:
        total = (total & 0xFFFF) + (total >> 16)
    return (~total) & 0xFFFF


class RawTcp:
    def __init__(self):
        self.sock = socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(0x0003))
        self.sock.bind((TAP, 0))
        self.host_mac = self.sock.getsockname()[4]
        self.client_next = (ISN + 1) & 0xFFFFFFFF
        self.server_next = 0
        self.timeout = 3.0
        self.pending = bytearray()
        self.ip_id = 0x5A5A
        self._handshake()

    def _frame(self, seq: int, ack: int, flags: int, payload: bytes = b"", options: bytes = b"") -> bytes:
        if len(options) % 4:
            options += b"\x01" * (4 - len(options) % 4)
        tcp_len = 20 + len(options)
        tcp = struct.pack(
            "!HHIIHHHH", SPORT, 443, seq & 0xFFFFFFFF, ack & 0xFFFFFFFF,
            ((tcp_len // 4) << 12) | flags, 65535, 0, 0
        ) + options + payload
        pseudo = HOST_IP + GUEST_IP + struct.pack("!BBH", 0, 6, len(tcp))
        tcp = tcp[:16] + struct.pack("!H", checksum(pseudo + tcp)) + tcp[18:]
        total = 20 + len(tcp)
        ip = struct.pack(
            "!BBHHHBBH4s4s", 0x45, 0, total, self.ip_id, 0, 64, 6, 0,
            HOST_IP, GUEST_IP
        )
        self.ip_id = (self.ip_id + 1) & 0xFFFF
        ip = ip[:10] + struct.pack("!H", checksum(ip)) + ip[12:]
        return b"\xff" * 6 + self.host_mac + b"\x08\x00" + ip + tcp

    def send_segment(self, seq: int, ack: int, flags: int, payload: bytes = b"", options: bytes = b""):
        self.sock.send(self._frame(seq, ack, flags, payload, options))

    def _parse(self, frame: bytes):
        if len(frame) < 54 or frame[12:14] != b"\x08\x00":
            return None
        if frame[23] != 6 or frame[26:30] != GUEST_IP or frame[30:34] != HOST_IP:
            return None
        ihl = (frame[14] & 15) * 4
        tcp = 14 + ihl
        if len(frame) < tcp + 20:
            return None
        if int.from_bytes(frame[tcp:tcp+2], "big") != 443:
            return None
        if int.from_bytes(frame[tcp+2:tcp+4], "big") != SPORT:
            return None
        thl = (frame[tcp+12] >> 4) * 4
        total = int.from_bytes(frame[16:18], "big")
        end = min(len(frame), 14 + total)
        if thl < 20 or end < tcp + thl:
            return None
        return {
            "seq": int.from_bytes(frame[tcp+4:tcp+8], "big"),
            "ack": int.from_bytes(frame[tcp+8:tcp+12], "big"),
            "flags": frame[tcp+13],
            "payload": frame[tcp+thl:end],
        }

    def _next_packet(self, timeout: float):
        ready, _, _ = select.select([self.sock], [], [], timeout)
        if not ready:
            return None
        deadline = time.monotonic() + 0.05
        while True:
            item = self._parse(self.sock.recv(65536))
            if item is not None:
                return item
            left = deadline - time.monotonic()
            if left <= 0:
                return None
            ready, _, _ = select.select([self.sock], [], [], left)
            if not ready:
                return None

    def _handshake(self):
        syn_options = b"\x02\x04\x02\x18"
        self.send_segment(ISN, 0, 0x02, options=syn_options)
        deadline = time.monotonic() + 3.0
        synack = None
        while time.monotonic() < deadline:
            item = self._next_packet(max(0.01, deadline - time.monotonic()))
            if item and (item["flags"] & 0x12) == 0x12:
                synack = item
                break
        if synack is None:
            raise ConnectionError("no SYN-ACK from local QEMU guest")
        self.server_next = (synack["seq"] + 1) & 0xFFFFFFFF
        self.send_segment(self.client_next, self.server_next, 0x10)

    def sendall(self, data: bytes):
        offset = 0
        while offset < len(data):
            chunk = data[offset:offset+1200]
            self.send_segment(self.client_next, self.server_next, 0x18, chunk)
            self.client_next = (self.client_next + len(chunk)) & 0xFFFFFFFF
            offset += len(chunk)

    def _consume(self, item):
        if item["flags"] & 0x04:
            raise ConnectionResetError("guest sent TCP RST")
        payload = item["payload"]
        seq = item["seq"]
        if payload:
            end = (seq + len(payload)) & 0xFFFFFFFF
            if seq == self.server_next:
                self.pending.extend(payload)
                self.server_next = end
            elif ((self.server_next - seq) & 0xFFFFFFFF) < len(payload):
                trim = (self.server_next - seq) & 0xFFFFFFFF
                self.pending.extend(payload[trim:])
                self.server_next = end
        if item["flags"] & 0x01:
            self.server_next = (self.server_next + 1) & 0xFFFFFFFF
        if payload or item["flags"] & 0x01:
            self.send_segment(self.client_next, self.server_next, 0x10)
        return item

    def wait_ack(self, timeout: float):
        deadline = time.monotonic() + timeout
        last = None
        while time.monotonic() < deadline:
            item = self._next_packet(max(0.01, deadline - time.monotonic()))
            if item is None:
                break
            self._consume(item)
            last = item["ack"]
            if last is not None:
                return last
        return last

    def recv(self, size: int) -> bytes:
        if self.pending:
            out = bytes(self.pending[:size])
            del self.pending[:size]
            return out
        deadline = time.monotonic() + self.timeout
        while time.monotonic() < deadline:
            item = self._next_packet(max(0.01, deadline - time.monotonic()))
            if item is None:
                break
            self._consume(item)
            if self.pending:
                out = bytes(self.pending[:size])
                del self.pending[:size]
                return out
        raise socket.timeout("raw TCP receive timed out")

    def settimeout(self, timeout: float):
        self.timeout = timeout

    def close(self):
        self.sock.close()


def main():
    raw = RawTcp()
    inc, out = ssl.MemoryBIO(), ssl.MemoryBIO()
    ctx = tlsclient.context()
    ctx.minimum_version = ssl.TLSVersion.TLSv1_3
    ctx.maximum_version = ssl.TLSVersion.TLSv1_3
    tls = ctx.wrap_bio(inc, out, server_hostname=tlsclient.NAME)
    try:
        while True:
            try:
                tls.do_handshake()
                break
            except ssl.SSLWantReadError:
                outgoing = out.read()
                if outgoing:
                    raw.sendall(outgoing)
                incoming = raw.recv(65536)
                inc.write(incoming)

        # Deliberately omit the client Finished bytes. The server's tested
        # application-record path accepts app traffic without this check.
        finished = out.read()
        if not finished:
            raise RuntimeError("OpenSSL produced no client Finished flight")
        tls.write(REQUEST)
        app_record = out.read()
        if len(app_record) < 32 or app_record[0] != 23:
            raise RuntimeError(f"unexpected application record: {len(app_record)} bytes")

        original_seq = raw.client_next
        prefix = bytearray(app_record[:16])
        prefix[-1] ^= 0x80  # authenticated ciphertext prefix is now invalid
        raw.send_segment(
            original_seq, (raw.server_next + 0x10000) & 0xFFFFFFFF, 0x18, bytes(prefix)
        )
        first_ack = raw.wait_ack(1.0)

        # Retransmit the original authenticated record at the same TCP sequence.
        # On the frozen target the prefix has already been consumed, so only the
        # suffix is appended to corrupted bytes. Fixed targets accept all bytes.
        raw.send_segment(original_seq, raw.server_next, 0x18, app_record)
        raw.client_next = (original_seq + len(app_record)) & 0xFFFFFFFF

        response = bytearray()
        deadline = time.monotonic() + 3.0
        while time.monotonic() < deadline:
            try:
                plain = tls.read(16384)
                if plain:
                    response.extend(plain)
                    if b"\r\n\r\n" in response:
                        break
            except ssl.SSLWantReadError:
                try:
                    inc.write(raw.recv(65536))
                except socket.timeout:
                    break
            except (ssl.SSLZeroReturnError, ssl.SSLError, ConnectionError, OSError):
                break

        got_http = response.startswith(b"HTTP/1.")
        expected_first_ack = (original_seq + len(prefix)) & 0xFFFFFFFF
        first_ack_matches = first_ack == expected_first_ack if EXPECT_DESYNC else first_ack == original_seq
        if first_ack is None or not first_ack_matches:
            raise SystemExit(
                f"FAIL: invalid-ACK TLS prefix ACK={first_ack!r}; "
                f"expected={'prefix end' if EXPECT_DESYNC else 'original sequence'}"
            )
        if got_http == EXPECT_DESYNC:
            raise SystemExit(
                f"FAIL: TLS response={got_http}; expected_http={not EXPECT_DESYNC}; "
                f"response_prefix={bytes(response[:80])!r}"
            )
        print(
            f"PASS: invalid-ACK TLS prefix advanced TCP={EXPECT_DESYNC}; "
            f"first_ack=0x{first_ack:08x}; http_response={got_http}; "
            f"app_record_bytes={len(app_record)}; prefix_bytes={len(prefix)}"
        )
    finally:
        raw.close()


if __name__ == "__main__":
    main()
